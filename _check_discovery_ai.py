"""Targeted checks of the new AI Discovery analysis.

The checks use fake frames and a fake provider, so no TikTok search and no
real AI call is made. They prove that the ranking follows the content, that
the cache stops a second call for the same video, and that a candidate whose
content cannot be read is never ranked.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import candidate_analysis as ca
from discover import DiscoveredVideo


def _video(url: str, creator: str = "creator_a") -> DiscoveredVideo:
    return DiscoveredVideo(
        source_url=url,
        title="AI music generated by Suno",
        creator=creator,
        views=1000,
        likes=100,
        comments=10,
        shares=5,
        download_url="https://example.invalid/video.mp4",
        source_name="AI Music",
        duration_seconds=20.0,
        posted_at="2026-11-01T10:00:00",
        topic="AI Music",
    )


def _good_payload() -> dict:
    return {
        "ai_music_fit": 18,
        "ai_music_fit_reason": "khung hình cho thấy pipeline Suno",
        "ai_music_fit_known": True,
        "music_quality": 16,
        "music_quality_reason": "giai điệu rõ, âm thanh sạch",
        "music_quality_known": True,
        "visual_quality": 13,
        "visual_quality_reason": "hình AI cinematic sắc nét",
        "visual_quality_known": True,
        "hook_retention": 12,
        "hook_retention_reason": "3 giây đầu có chuyển cảnh mạnh",
        "hook_retention_known": True,
        "engagement_virality": 11,
        "engagement_virality_reason": "dễ chia sẻ, khung hình đẹp",
        "engagement_virality_known": True,
        "creativity": 8,
        "creativity_reason": "ý tưởng lạ",
        "creativity_known": True,
        "channel_fit": 5,
        "channel_fit_reason": "đúng thị trường AI music",
        "channel_fit_known": True,
        "content_summary": "Video nhạc AI với hình ảnh cinematic.",
        "content_ai_visual": True,
        "content_is_ai_music": True,
    }


def check(name: str, condition: bool, detail: str = "") -> None:
    mark = "PASS" if condition else "FAIL"
    print(f"[{mark}] {name}" + (f" — {detail}" if detail else ""))
    if not condition:
        raise SystemExit(1)


def main() -> None:
    print("== 1. weights sum to 100 and match the required 7 criteria ==")
    check("7 dimensions", len(ca.DIMENSION_POINTS) == 7, str(len(ca.DIMENSION_POINTS)))
    check("weights sum 100", sum(ca.DIMENSION_POINTS.values()) == 100,
          str(sum(ca.DIMENSION_POINTS.values())))
    expected = {
        ca.DIMENSION_AI_FIT: 20,
        ca.DIMENSION_MUSIC: 20,
        ca.DIMENSION_VISUAL: 15,
        ca.DIMENSION_HOOK: 15,
        ca.DIMENSION_VIRAL: 15,
        ca.DIMENSION_CREATIVITY: 10,
        ca.DIMENSION_CHANNEL: 5,
    }
    check("exact weights", ca.DIMENSION_POINTS == expected, str(ca.DIMENSION_POINTS))

    print("\n== 2. a candidate without content is NOT ranked ==")
    with tempfile.TemporaryDirectory() as tmp:
        cache_path = Path(tmp) / "cache.json"
        calls: list[str] = []

        def reader(video: DiscoveredVideo) -> list[bytes]:
            calls.append(video.source_url)
            return []

        analyses = ca.analyze_candidates(
            [_video("https://tiktok.test/1")],
            "AI Music",
            frame_reader=reader,
            cache_path=cache_path,
        )
        check("one analysis returned", len(analyses) == 1)
        check("not ranked", analyses[0].ranked is False)
        check("rank stays 0", analyses[0].rank == 0)
        check("marked insufficient", ca.INSUFFICIENT_DATA in analyses[0].summary,
              analyses[0].summary[:70])
        check("no score claimed", analyses[0].score == 0)
        check("best_analysis is None", ca.best_analysis(analyses) is None)

    print("\n== 3. content analysis scores the 7 dimensions ==")
    analysis = ca.analyze_candidate(
        _video("https://tiktok.test/2"),
        "AI Music",
        frames=[b"frame1", b"frame2", b"frame3"],
        content_payload=_good_payload(),
        provider="gemini",
        model="gemini-test",
    )
    check("ranked", analysis.ranked is True)
    check("content analyzed", analysis.content_analyzed is True)
    check("3 frames counted", analysis.frame_count == 3)
    check("7 dimensions", len(analysis.dimensions) == 7, str(len(analysis.dimensions)))
    check("score is 83", analysis.score == 83, str(analysis.score))
    check("max points 100", sum(d.max_points for d in analysis.dimensions) == 100)
    check("points match score", sum(d.points for d in analysis.dimensions) == analysis.score)
    check("ai fit is 18/20", analysis.dimensions[0].points == 18)
    check("views only auxiliary", "tín hiệu bổ trợ" in analysis.summary)

    print("\n== 4. a dimension the provider cannot decide keeps no points ==")
    payload = _good_payload()
    payload["music_quality_known"] = False
    payload["music_quality_reason"] = ""
    partial = ca.analyze_candidate(
        _video("https://tiktok.test/3"), "AI Music", frames=[b"f"], content_payload=payload
    )
    music_dim = next(d for d in partial.dimensions if d.name == ca.DIMENSION_MUSIC)
    check("music unknown", music_dim.known is False)
    check("music points 0", music_dim.points == 0)
    check("music marked", music_dim.detail == ca.INSUFFICIENT_DATA, music_dim.detail)
    check("score dropped to 67", partial.score == 67, str(partial.score))

    print("\n== 5. the cache stops a second AI call for the same video ==")
    with tempfile.TemporaryDirectory() as tmp:
        cache_path = Path(tmp) / "cache.json"
        ai_calls: list[str] = []

        def fake_request(frames, metadata, *, model="", provider=""):
            ai_calls.append(metadata["title"])
            return _good_payload()

        original = ca.request_content_analysis
        ca.request_content_analysis = fake_request
        try:
            def reader(video: DiscoveredVideo) -> list[bytes]:
                return [b"real-frame-a", b"real-frame-b"]

            first = ca.analyze_candidates(
                [_video("https://tiktok.test/4")],
                "AI Music",
                frame_reader=reader,
                cache_path=cache_path,
            )
            check("first run called AI once", len(ai_calls) == 1, str(len(ai_calls)))
            check("first run ranked", first[0].ranked is True)
            check("cache file written", cache_path.exists())

            second = ca.analyze_candidates(
                [_video("https://tiktok.test/4")],
                "AI Music",
                frame_reader=reader,
                cache_path=cache_path,
            )
            check("second run did NOT call AI", len(ai_calls) == 1, str(len(ai_calls)))
            check("second run still ranked", second[0].ranked is True)
            check("same score", second[0].score == first[0].score)

            saved = json.loads(cache_path.read_text(encoding="utf-8"))
            # The cache holds the verdict under the key of the analyzer that
            # made it, and the frames under the plain key, so the next
            # analyzer finds the frames without reading the media again.
            verdicts = [
                k for k, v in saved.items() if (v or {}).get("payload")
            ]
            check("cache has one verdict", len(verdicts) == 1, str(verdicts))
            check(
                "the verdict key carries the analyzer version",
                verdicts and verdicts[0].startswith("local:"),
                str(verdicts),
            )
            check(
                "the frames are kept under the plain key",
                len(saved) == 2,
                str(len(saved)),
            )
        finally:
            ca.request_content_analysis = original

    print("\n== 6. the best video is the top content-ranked one ==")
    with tempfile.TemporaryDirectory() as tmp:
        cache_path = Path(tmp) / "cache.json"
        videos = [
            _video("https://tiktok.test/low", "low_creator"),
            _video("https://tiktok.test/high", "high_creator"),
        ]

        original = ca.request_content_analysis
        state = {"n": 0}

        def sequenced(frames, metadata, *, model="", provider=""):
            state["n"] += 1
            if state["n"] == 1:
                return _good_payload()
            payload = _good_payload()
            payload["ai_music_fit"] = 12
            payload["ai_music_fit_reason"] = "dấu hiệu AI vừa phải"
            return payload

        ca.request_content_analysis = sequenced
        try:
            analyses = ca.analyze_candidates(
                videos,
                "AI Music",
                frame_reader=lambda v: [b"f1", b"f2"],
                cache_path=cache_path,
            )
            check("both ranked", all(a.ranked for a in analyses))
            check("rank 1 is first", analyses[0].rank == 1)
            check("rank 2 is second", analyses[1].rank == 2)
            check("first has higher score", analyses[0].score > analyses[1].score,
                  f"{analyses[0].score} vs {analyses[1].score}")
            check("best_analysis is rank 1", ca.best_analysis(analyses) is analyses[0])
            check("both relevant", all(a.content_relevant is True for a in analyses))
        finally:
            ca.request_content_analysis = original

    print("\n== 7. engagement is auxiliary and never decides alone ==")
    low_views = _video("https://tiktok.test/many")
    low_views.views = 5_000_000
    low_views.likes = 1
    low_views.comments = 0
    low_views.shares = 0
    analysis = ca.analyze_candidate(
        low_views, "AI Music", frames=[b"f"], content_payload=_good_payload()
    )
    check("score comes from content", analysis.score == 83, str(analysis.score))
    check("views only auxiliary", "5,000,000" in analysis.summary, analysis.summary[-120:])

    print("\n== 8. a video whose content is NOT AI Music is rejected ==")
    with tempfile.TemporaryDirectory() as tmp:
        cache_path = Path(tmp) / "cache.json"
        car_payload = _good_payload()
        car_payload["ai_music_fit"] = 0
        car_payload["ai_music_fit_reason"] = "video cho thấy xe ô tô, không có nhạc"
        car_payload["content_is_ai_music"] = False
        car_payload["content_summary"] = "Video quay xe ô tô."
        car_payload["content_ai_visual"] = False

        original = ca.request_content_analysis
        ca.request_content_analysis = lambda f, m, model="", provider="": car_payload
        try:
            analyses = ca.analyze_candidates(
                [_video("https://tiktok.test/car")],
                "AI Music",
                frame_reader=lambda v: [b"f1"],
                cache_path=cache_path,
            )
            a = analyses[0]
            check("not relevant", a.content_relevant is False)
            check("not ranked", a.ranked is False)
            check("no rank", a.rank == 0)
            check("score zero", a.score == 0)
            check("reason kept", "ô tô" in a.content_relevance_reason,
                  a.content_relevance_reason)
            check("best_analysis is None", ca.best_analysis(analyses) is None)
        finally:
            ca.request_content_analysis = original

    print("\n== 9. a video the AI cannot judge stays undecided, not accepted ==")
    with tempfile.TemporaryDirectory() as tmp:
        cache_path = Path(tmp) / "cache.json"
        unclear = _good_payload()
        unclear["ai_music_fit_known"] = False
        unclear["ai_music_fit"] = 0
        unclear["ai_music_fit_reason"] = ""
        unclear.pop("content_is_ai_music", None)

        original = ca.request_content_analysis
        ca.request_content_analysis = lambda f, m, model="", provider="": unclear
        try:
            analyses = ca.analyze_candidates(
                [_video("https://tiktok.test/unclear")],
                "AI Music",
                frame_reader=lambda v: [b"f1"],
                cache_path=cache_path,
            )
            a = analyses[0]
            check("relevance unknown", a.content_relevant is None)
            check("not ranked", a.ranked is False)
            check("no rank", a.rank == 0)
            check("not accepted", ca.best_analysis(analyses) is None)
            check("marked insufficient", ca.INSUFFICIENT_DATA in a.insufficient_reason
                  or ca.INSUFFICIENT_DATA in a.summary, a.insufficient_reason)
        finally:
            ca.request_content_analysis = original

    print("\nALL TARGETED CHECKS PASSED")


if __name__ == "__main__":
    main()
