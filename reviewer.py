"""P3 content reviewer, revisions, and learned corrections."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Callable
import time

from brain import (
    AnalysisResult,
    BrainError,
    MAX_REVISIONS,
    TEMPLATE_PROVIDER_NAME,
    analyze_media,
    create_provider,
)

PASSING_SCORE = 70
LEARNED_RULES_PATH = Path("learned_rules.md")


class ReviewerError(RuntimeError):
    """Raised when review cannot be completed safely."""


def score_result(result: AnalysisResult, score: int | None = None, reason: str | None = None) -> AnalysisResult:
    """Apply a reviewer score and reason to an analysis result."""
    if score is not None:
        result.score = max(0, min(100, int(score)))
    if reason is not None:
        result.score_reason = reason.strip()
    return result


def save_correction(
    task_id: str,
    result: AnalysisResult,
    reason: str,
    path: Path = LEARNED_RULES_PATH,
) -> None:
    """Append a correction learned from reviewer feedback."""
    correction = reason.strip() or result.score_reason.strip() or "No reason supplied"
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as rules_file:
        rules_file.write(f"- Task `{task_id}`: {correction}\n")


def review_result(result: AnalysisResult) -> AnalysisResult:
    """Mark a result accepted or rejected based on its score."""
    if result.status == "FAILED_RETRYABLE":
        return result
    if result.score < PASSING_SCORE:
        result.status = "REJECTED"
        if not result.score_reason:
            result.score_reason = f"Score {result.score} is below the minimum {PASSING_SCORE}"
        return result
    result.status = "ACCEPTED"
    return result


def mark_non_ai(result: AnalysisResult) -> AnalysisResult:
    """Mark a result that was produced without an AI provider."""
    if result.provider == TEMPLATE_PROVIDER_NAME:
        result.status = "NON_AI_TEMPLATE" if result.status == "ACCEPTED" else result.status
        note = "Generated by the template provider, not by an AI model."
        if note not in result.score_reason:
            result.score_reason = f"{result.score_reason} | {note}".strip(" |")
    return result


def review_with_revisions(
    task_id: str,
    metadata: dict[str, Any],
    config: dict[str, Any],
    *,
    provider: Any = None,
    frames: list[bytes] | None = None,
    reviewer: Callable[[AnalysisResult], AnalysisResult] = score_result,
    learned_rules_path: Path = LEARNED_RULES_PATH,
    max_revisions: int = MAX_REVISIONS,
    usage: Any = None,
    sleep: Any = None,
) -> AnalysisResult:
    """Analyse, score, and revise content up to five times before rejection."""
    if max_revisions < 0 or max_revisions > MAX_REVISIONS:
        raise ReviewerError(f"max_revisions must be between 0 and {MAX_REVISIONS}")

    result = analyze_media(metadata, config, provider=provider, frames=frames, usage=usage, sleep=sleep or time.sleep)
    if result.status == "FAILED_RETRYABLE":
        return result

    result = reviewer(result)
    result = review_result(result)
    result = mark_non_ai(result)
    revision = 0
    while result.status == "REJECTED" and revision < max_revisions:
        save_correction(task_id, result, result.score_reason, learned_rules_path)
        instruction = (
            "Revise the content to address the reviewer reason while preserving the facts. "
            f"Reviewer reason: {result.score_reason}"
        )
        candidate = analyze_media(
            metadata,
            config,
            provider=provider,
            frames=frames,
            instruction=instruction,
            usage=result.usage,
            sleep=sleep or time.sleep,
        )
        if candidate.status == "FAILED_RETRYABLE":
            candidate.status = "FAILED_RETRYABLE"
            candidate.error = candidate.error or "Revision failed and is retryable"
            return candidate
        candidate = reviewer(candidate)
        candidate = review_result(candidate)
        candidate = mark_non_ai(candidate)
        result = candidate
        revision += 1

    if result.status == "REJECTED":
        result.error = (
            f"Rejected after {revision} revisions; score {result.score} remains below {PASSING_SCORE}. "
            f"Reason: {result.score_reason}"
        )
    return result


